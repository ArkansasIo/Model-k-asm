; Model K file I/O reference interface
FILE_OPEN: MOV R0, PATH_PTR
 CALL OS_OPEN
 MOV FH, R0
 RET
FILE_READ: MOV R0, FH
 MOV R1, BUFFER_PTR
 MOV R2, BYTE_COUNT
 CALL OS_READ
 RET
FILE_WRITE: MOV R0, FH
 MOV R1, BUFFER_PTR
 MOV R2, BYTE_COUNT
 CALL OS_WRITE
 RET
FILE_CLOSE: MOV R0, FH
 CALL OS_CLOSE
 RET
