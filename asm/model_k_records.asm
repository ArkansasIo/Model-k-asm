; Model K 20-byte record operations
RECORD_READ: MOV R0, RECORD_INDEX
 MUL R0, #20
 ADD R0, RECORD_BASE
 CALL CORE_READ_BLOCK_20
 CALL RECORD_CHECKSUM
 RET
RECORD_WRITE: CALL RECORD_VALIDATE
 JNZ RECORD_ERROR
 MOV R0, RECORD_INDEX
 MUL R0, #20
 ADD R0, RECORD_BASE
 CALL CORE_WRITE_BLOCK_20
 RET
RECORD_CHECKSUM: CLR R7
 MOV R6, #20
RC_LOOP: LOADB R0, R1
 ADD R7, R0
 INC R1
 DEC R6
 JNZ RC_LOOP
 RET
