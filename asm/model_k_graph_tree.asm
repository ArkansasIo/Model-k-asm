; Model K graph/tree primitives
TREE_SEARCH: MOV NODE, ROOT
TS_LOOP: CMP NODE, #0
 JEQ TS_NOT_FOUND
 LOAD R1, [NODE+KEY]
 CMP R0, R1
 JEQ TS_FOUND
 JLT TS_LEFT
 LOAD NODE, [NODE+RIGHT]
 JMP TS_LOOP
TS_LEFT: LOAD NODE, [NODE+LEFT]
 JMP TS_LOOP
TS_FOUND: MOV R0, NODE
 RET
TS_NOT_FOUND: CLR R0
 RET
GRAPH_BFS: CALL QUEUE_INIT
 CALL VISIT_CLEAR
 CALL QUEUE_PUSH, START_NODE
GBFS_LOOP: CALL QUEUE_POP
 JZ GBFS_DONE
 MOV NODE, R0
 CALL VISIT_SET
 CALL EDGE_ITERATE
GBFS_EDGE: CALL EDGE_NEXT
 JZ GBFS_LOOP
 CALL VISIT_TEST
 JNZ GBFS_EDGE
 CALL QUEUE_PUSH, EDGE_NODE
 JMP GBFS_EDGE
GBFS_DONE: RET
