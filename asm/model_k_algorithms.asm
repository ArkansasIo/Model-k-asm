; Model K general algorithm library
BINARY_SEARCH: MOV LO, #0
 MOV HI, ARRAY_LEN
BS_LOOP: CMP LO, HI
 JGE BS_NOT_FOUND
 ADD MID, LO, HI
 SHR MID, #1
 LOAD R0, ARRAY[MID]
 CMP R0, KEY
 JEQ BS_FOUND
 JLT BS_RIGHT
 MOV HI, MID
 JMP BS_LOOP
BS_RIGHT: INC MID
 MOV LO, MID
 JMP BS_LOOP
BS_FOUND: MOV R0, MID
 RET
BS_NOT_FOUND: MOV R0, #-1
 RET
CHECKSUM8: CLR R0
 MOV R1, LENGTH
CS_LOOP: LOADB R2, [PTR]
 ADD R0, R2
 INC PTR
 DEC R1
 JNZ CS_LOOP
 RET
GCD: CMP R1, #0
 JEQ GCD_DONE
 MOD R0, R1
 XCHG R0, R1
 JMP GCD
GCD_DONE: RET
