-- Model K: 20-bit logical record for MySQL 8.x
CREATE DATABASE IF NOT EXISTS model_k;
USE model_k;

DROP TABLE IF EXISTS model_k_20bit_records;
CREATE TABLE model_k_20bit_records (
    record_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    value20 INT UNSIGNED NOT NULL,
    flags TINYINT UNSIGNED NOT NULL DEFAULT 0,
    version TINYINT UNSIGNED NOT NULL DEFAULT 1,
    checksum8 TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (record_id),
    CONSTRAINT chk_value20 CHECK (value20 BETWEEN 0 AND 1048575)
);

DELIMITER //

CREATE FUNCTION mk20_mask(v INT UNSIGNED) RETURNS INT UNSIGNED DETERMINISTIC
BEGIN RETURN v & 1048575; END//

CREATE FUNCTION mk20_add(a INT UNSIGNED,b INT UNSIGNED) RETURNS INT UNSIGNED DETERMINISTIC
BEGIN RETURN (a+b) & 1048575; END//

CREATE FUNCTION mk20_xor(a INT UNSIGNED,b INT UNSIGNED) RETURNS INT UNSIGNED DETERMINISTIC
BEGIN RETURN (a ^ b) & 1048575; END//

CREATE FUNCTION mk20_and(a INT UNSIGNED,b INT UNSIGNED) RETURNS INT UNSIGNED DETERMINISTIC
BEGIN RETURN (a & b) & 1048575; END//

CREATE FUNCTION mk20_or(a INT UNSIGNED,b INT UNSIGNED) RETURNS INT UNSIGNED DETERMINISTIC
BEGIN RETURN (a | b) & 1048575; END//

CREATE FUNCTION mk20_not(a INT UNSIGNED) RETURNS INT UNSIGNED DETERMINISTIC
BEGIN RETURN (~a) & 1048575; END//

CREATE FUNCTION mk20_checksum8(v INT UNSIGNED,flags8 INT UNSIGNED) RETURNS TINYINT UNSIGNED DETERMINISTIC
BEGIN RETURN (v+flags8) & 255; END//

CREATE PROCEDURE mk20_insert(IN p_value INT UNSIGNED,IN p_flags TINYINT UNSIGNED)
BEGIN
 INSERT INTO model_k_20bit_records(value20,flags,checksum8)
 VALUES (p_value & 1048575,p_flags,mk20_checksum8(p_value,p_flags));
END//

DELIMITER ;

