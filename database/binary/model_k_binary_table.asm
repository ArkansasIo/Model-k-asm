; Model K MKTB binary table I/O
TABLE_OPEN:
    CALL READ_HEADER
    CMP TABLE_MAGIC, "MKTB"
    JNE TABLE_ERROR
    CMP TABLE_RECORD_SIZE, #20
    JNE TABLE_ERROR
    RET

TABLE_RECORD_ADDRESS:
    MOV R0, RECORD_INDEX
    MUL R0, #20
    ADD R0, #32
    RET

TABLE_READ:
    CALL TABLE_RECORD_ADDRESS
    CALL CORE_READ_BLOCK_20
    CALL VERIFY_RECORD_CHECKSUM
    RET

TABLE_WRITE:
    CALL VALIDATE_RECORD
    CALL TABLE_RECORD_ADDRESS
    CALL CORE_WRITE_BLOCK_20
    RET
