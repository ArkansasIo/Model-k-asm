; Model K patch engine
PATCH_VERIFY:
    CALL READ_PATCH_MANIFEST
    CALL VERIFY_SOURCE_VERSION
    CALL VERIFY_DEPENDENCIES
    CALL VERIFY_OLD_HASHES
    RET

PATCH_APPLY:
    CALL PATCH_VERIFY
    CALL CREATE_ROLLBACK_POINT
    CALL APPLY_FILE_OPERATIONS
    CALL VERIFY_NEW_HASHES
    CALL WRITE_UPDATE_RECORD
    RET

PATCH_ROLLBACK:
    CALL LOAD_ROLLBACK_POINT
    CALL RESTORE_FILES
    CALL VERIFY_ROLLBACK
    RET
