; Model K update manager
UPDATE_CHECK:
    CALL LOAD_UPDATE_INDEX
    CALL COMPARE_VERSIONS
    CALL RESOLVE_DEPENDENCIES
    RET

UPDATE_INSTALL:
    CALL UPDATE_CHECK
    CALL DOWNLOAD_OR_LOAD_PACKAGE
    CALL PATCH_VERIFY
    CALL PATCH_APPLY
    RET

UPDATE_STATUS:
    CALL READ_UPDATE_HISTORY
    CALL PRINT_UPDATE_STATE
    RET
